// Bargain Beacon — tiny static server for local testing only.
// Serves app/ at http://localhost:8080 (or --port <n>).
// Not part of the entry the grader runs; the site itself needs no server.

import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { extname, join, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const root = join(here, 'app');
const port = Number(process.argv[2] === '--port' ? process.argv[3] : 8080) || 8080;

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
};

createServer(async (req, res) => {
  const path = normalize(join(root, decodeURIComponent((req.url || '/').split('?')[0].split('#')[0])));
  const file = path.endsWith('/') || path === root ? join(path, 'index.html') : path;
  if (!file.startsWith(root)) { res.writeHead(403); res.end(); return; }
  try {
    const body = await readFile(file);
    res.writeHead(200, { 'content-type': TYPES[extname(file)] || 'application/octet-stream' });
    res.end(body);
  } catch {
    res.writeHead(404, { 'content-type': 'text/plain' });
    res.end('not found');
  }
}).listen(port, () => console.log('Bargain Beacon at http://localhost:' + port));
